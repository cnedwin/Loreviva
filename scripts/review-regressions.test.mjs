test('actual Git Windows clean and checkout preserve canonical source and regenerated bytes',async()=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'loreviva-checkout-'));
 // The source-derived standalone validators exceed spawnSync's 1 MiB default.
 // Keep the byte comparison intact and bound capture above the generated file.
 const git=(args,input)=>{const result=spawnSync('git',['-c','core.autocrlf=true',...args],{cwd:root,input,maxBuffer:16*1024*1024});assert.equal(result.status,0,result.error?.message??result.stderr?.toString());return result.stdout};
 const hash=data=>createHash('sha256').update(data).digest('hex');
 try {
  git(['init','--quiet']);
  await cp(path.join(repo,'.gitattributes'),path.join(root,'.gitattributes'));
  const generated=await generateContracts({sourceRoot:canonicalSourceRoot,outputRoot:path.join(root,'source')});
  const manifest=JSON.parse(await readFile(path.join(repo,'contracts/generated/manifest.json'),'utf8'));
  const sources=Object.keys(manifest.source_hashes).map(name=>'contracts/source/'+name);
  const before={},after={};
  for(const output of [...sources,...generated.outputs]){
   const data=await readFile(path.join(sources.includes(output)?repo:path.join(root,'source'),output));
   const oid=git(['hash-object','-w','--path='+output,'--stdin'],data).toString().trim();
   const checkout=git(['cat-file','--filters','--path='+output,oid]);
   await mkdir(path.dirname(path.join(root,'checkout',output)),{recursive:true});await writeFile(path.join(root,'checkout',output),checkout);
   assert.equal(checkout.includes(Buffer.from('\r\n')),false,output+' converted to CRLF');
   before[output]=hash(data);after[output]=hash(checkout);
  }
  const checkedSource=path.join(root,'checkout/contracts/source');
  const regenerated=await generateContracts({sourceRoot:checkedSource,outputRoot:path.join(root,'regenerated')});
  for(const output of regenerated.outputs){
   before['regenerated/'+output]=before[output];
   after['regenerated/'+output]=hash(await readFile(path.join(root,'regenerated',output)));
  }
  assert.deepEqual(after,before,'Git clean/checkout or regeneration changed canonical bytes');
  assert.deepEqual(await checkGenerated({sourceRoot:checkedSource,outputRoot:path.join(root,'checkout')}),[]);
 } finally {await rm(root,{recursive:true,force:true})}
});
