import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtemp,readFile,writeFile,mkdir,rm,cp} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {generateContracts,canonicalSourceRoot} from './generate-contracts.mjs';
import {checkGenerated} from './check-generated.mjs';
const repo=fileURLToPath(new URL('../',import.meta.url));
test('source-only independent checkout regenerates without authority-root ancestors',async()=>{
 assert.equal(canonicalSourceRoot,path.resolve(repo,'contracts/source'));
 const root=await mkdtemp(path.join(os.tmpdir(),'loreviva-independent-'));
 try {
  await cp(path.join(repo,'scripts'),path.join(root,'scripts'),{recursive:true});
  await cp(canonicalSourceRoot,path.join(root,'contracts/source'),{recursive:true});
  await cp(path.join(repo,'node_modules'),path.join(root,'node_modules'),{recursive:true,dereference:true});
  const localRequire=createRequire(import.meta.url);
  const require=createRequire(localRequire.resolve('ajv'));
  for(const name of ['fast-deep-equal','fast-uri','json-schema-traverse','require-from-string'])
   await cp(path.dirname(require.resolve(name+'/package.json')),path.join(root,'node_modules',name),{recursive:true,dereference:true});
  const result=spawnSync(process.execPath,['scripts/generate-contracts.mjs'],{cwd:root,encoding:'utf8'});
  assert.equal(result.status,0,result.stdout+result.stderr);
  const original=JSON.parse(await readFile(path.join(repo,'contracts/generated/manifest.json'),'utf8'));
  const isolated=JSON.parse(await readFile(path.join(root,'contracts/generated/manifest.json'),'utf8'));
  assert.deepEqual(isolated.source_hashes,original.source_hashes);
 }finally{await rm(root,{recursive:true,force:true})}
});
